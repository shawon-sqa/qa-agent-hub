/**
 * Generates simulated worker execution logs
 */
export function generateWorkerLogs(
  specs: PlaywrightSpecFile[],
  project: ProjectOption
): PlaywrightExecutionLog[] {
  const logs: PlaywrightExecutionLog[] = [];
  const now = new Date();

  logs.push({
    id: "log_0",
    timestamp: new Date(now.getTime() - 4000).toLocaleTimeString(),
    level: "info",
    workerId: 1,
    message: `[Playwright Runner] Initializing test workers for ${project.name}...`,
  });

  logs.push({
    id: "log_1",
    timestamp: new Date(now.getTime() - 3500).toLocaleTimeString(),
    level: "info",
    workerId: 1,
    message: `[Worker 1] Launched Chromium v128.0 (headless=true, viewport=1280x720)`,
  });

  specs.forEach((s, idx) => {
    const workerId = (idx % 3) + 1;
    logs.push({
      id: `log_spec_${idx}_start`,
      timestamp: new Date(now.getTime() - 3000 + idx * 800).toLocaleTimeString(),
      level: "step",
      workerId,
      message: `[Worker ${workerId}] Running: ${s.filename} -> "${s.title}"`,
    });

    logs.push({
      id: `log_spec_${idx}_nav`,
      timestamp: new Date(now.getTime() - 2500 + idx * 800).toLocaleTimeString(),
      level: "step",
      workerId,
      message: `[Worker ${workerId}] Navigating to https://${project.domain} (HTTP 200 OK, 142ms)`,
    });

    logs.push({
      id: `log_spec_${idx}_assert`,
      timestamp: new Date(now.getTime() - 2000 + idx * 800).toLocaleTimeString(),
      level: "pass",
      workerId,
      message: `[Worker ${workerId}] ✓ Assertions passed: DOM verified, elements visible (${s.durationMs || 1200}ms)`,
    });
  });

  logs.push({
    id: "log_final",
    timestamp: now.toLocaleTimeString(),
    level: "pass",
    workerId: 1,
    message: `[Playwright Runner] All ${specs.length} spec suites passed successfully. Traces recorded to .playwright/traces/`,
  });

  return logs;
}

