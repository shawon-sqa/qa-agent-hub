/**
 * Generates Page Object Models (POM) tailored to the active project
 */
export function generatePageObjects(project: ProjectOption): PlaywrightPageObject[] {
  const isEcommerce =
    project.name.toLowerCase().includes("commerce") ||
    project.name.toLowerCase().includes("checkout") ||
    project.name.toLowerCase().includes("store");

  const loginPageCode = `import { Page, Locator, expect } from '@playwright/test';

/**
 * Page Object Model for User Authentication
 * Generated by QA Agent Hub for ${project.name}
 */
export class LoginPage {
  readonly page: Page;
  readonly usernameInput: Locator;
  readonly passwordInput: Locator;
  readonly loginButton: Locator;
  readonly errorMessage: Locator;
  readonly userAvatar: Locator;

  constructor(page: Page) {
    this.page = page;
    this.usernameInput = page.locator('input[type="email"], input[name="username"]');
    this.passwordInput = page.locator('input[type="password"]');
    this.loginButton = page.locator('button[type="submit"], button:has-text("Sign In")');
    this.errorMessage = page.locator('.alert-error, [role="alert"]');
    this.userAvatar = page.locator('[data-testid="user-avatar"], .profile-icon');
  }

  async goto() {
    await this.page.goto('/login');
    await expect(this.loginButton).toBeVisible();
  }

  async login(username: string, password: string) {
    await this.usernameInput.fill(username);
    await this.passwordInput.fill(password);
    await this.loginButton.click();
  }

  async assertLoginSuccess() {
    await expect(this.userAvatar).toBeVisible({ timeout: 5000 });
  }

  async assertErrorMessage(expectedText: string) {
    await expect(this.errorMessage).toContainText(expectedText);
  }
}
`;

  const checkoutPageCode = `import { Page, Locator, expect } from '@playwright/test';

/**
 * Page Object Model for Cart & Checkout Workflows
 * Generated by QA Agent Hub for ${project.name}
 */
export class CheckoutPage {
  readonly page: Page;
  readonly cartItems: Locator;
  readonly couponInput: Locator;
  readonly applyCouponButton: Locator;
  readonly checkoutButton: Locator;
  readonly shippingAddressInput: Locator;
  readonly paymentMethodSelect: Locator;
  readonly placeOrderButton: Locator;
  readonly orderConfirmationBanner: Locator;

  constructor(page: Page) {
    this.page = page;
    this.cartItems = page.locator('[data-testid="cart-item"], .cart-item');
    this.couponInput = page.locator('input[name="couponCode"], #discount-code');
    this.applyCouponButton = page.locator('button:has-text("Apply")');
    this.checkoutButton = page.locator('button:has-text("Proceed to Checkout")');
    this.shippingAddressInput = page.locator('input[name="shippingAddress"]');
    this.paymentMethodSelect = page.locator('select[name="paymentMethod"]');
    this.placeOrderButton = page.locator('button:has-text("Place Order")');
    this.orderConfirmationBanner = page.locator('.order-success, [data-testid="order-confirmed"]');
  }

  async applyDiscount(coupon: string) {
    await this.couponInput.fill(coupon);
    await this.applyCouponButton.click();
    await this.page.waitForResponse((res) => res.url().includes('/api') && res.status() === 200);
  }

  async completeCheckout(address: string, paymentMethod: string) {
    await this.checkoutButton.click();
    await this.shippingAddressInput.fill(address);
    await this.paymentMethodSelect.selectOption(paymentMethod);
    await this.placeOrderButton.click();
  }

  async assertOrderPlaced() {
    await expect(this.orderConfirmationBanner).toBeVisible({ timeout: 8000 });
  }
}
`;

  return [
    {
      id: "pom_1",
      name: "Authentication Page Object",
      filename: "LoginPage.ts",
      className: "LoginPage",
      description: "Encapsulates form inputs, sign-in CTA buttons, and authentication error assertions.",
      locators: [
        { name: "usernameInput", selector: 'input[type="email"], input[name="username"]', description: "Email or username field" },
        { name: "passwordInput", selector: 'input[type="password"]', description: "Account password input" },
        { name: "loginButton", selector: 'button[type="submit"]', description: "Primary login CTA" },
        { name: "errorMessage", selector: '.alert-error, [role="alert"]', description: "Feedback banner on auth error" },
      ],
      actions: [
        { name: "goto", params: [], code: "await this.page.goto('/login');", description: "Navigate to login screen" },
        { name: "login", params: ["username", "password"], code: "await this.usernameInput.fill(username); ...", description: "Submit credentials" },
      ],
      code: loginPageCode,
    },
    {
      id: "pom_2",
      name: isEcommerce ? "Checkout & Cart Page Object" : "Dashboard & Navigation Page Object",
      filename: isEcommerce ? "CheckoutPage.ts" : "DashboardPage.ts",
      className: isEcommerce ? "CheckoutPage" : "DashboardPage",
      description: "Encapsulates order placement, promotions, and state validation.",
      locators: [
        { name: "cartItems", selector: '[data-testid="cart-item"]', description: "Rendered product items" },
        { name: "couponInput", selector: 'input[name="couponCode"]', description: "Discount voucher input" },
        { name: "checkoutButton", selector: 'button:has-text("Proceed to Checkout")', description: "Proceed button" },
      ],
      actions: [
        { name: "applyDiscount", params: ["coupon"], code: "await this.couponInput.fill(coupon); ...", description: "Apply promotion voucher" },
      ],
      code: checkoutPageCode,
    },
  ];
}

/**
 * Generates Playwright E2E spec files from active project test cases
 */
export function generatePlaywrightSpecs(
  project: ProjectOption,
  testCases: FunctionalTestCase[]
): PlaywrightSpecFile[] {
  const specs: PlaywrightSpecFile[] = [];

  const e2eCases = testCases.filter((tc) => tc.type === "e2e").slice(0, 4);
  const items = e2eCases.length > 0 ? e2eCases : testCases.slice(0, 3);

  items.forEach((tc, idx) => {
    const filename = `${tc.testCaseId.toLowerCase().replace(/[^a-z0-9]/g, "-")}.spec.ts`;

    const specCode = `import { test, expect } from '@playwright/test';
import { LoginPage } from '../pages/LoginPage';

/**
 * Test Spec: ${tc.testCaseId} - ${tc.title}
 * Module: ${tc.module} | Priority: ${tc.priority}
 * Target: https://${project.domain}
 */
test.describe('${tc.module} - E2E Verification Suite', () => {
  let loginPage: LoginPage;

  test.beforeEach(async ({ page }) => {
    loginPage = new LoginPage(page);
    await page.goto('/');
    // Wait for critical resources
    await page.waitForLoadState('domcontentloaded');
  });

  test('${tc.title}', async ({ page }) => {
    // Step 1: Verification of initial navigation
    await expect(page).toHaveURL(/.*${project.domain.split(".")[0]}/i);

    // Step 2: Preconditions
    ${tc.preconditions.map((p) => `// Precondition: ${p}`).join("\n    ")}

    // Step 3: Executing procedural steps
    ${tc.steps
      .map(
        (s) =>
          `// Step ${s.stepNumber}: ${s.action}\n    // Expected: ${s.expectedResult}\n    await page.waitForTimeout(100);`
      )
      .join("\n\n    ")}

    // Step 4: Final Assertion
    await expect(page.locator('body')).toBeVisible();
  });
});
`;

    specs.push({
      id: `spec_${idx + 1}`,
      testCaseCode: tc.testCaseId,
      title: tc.title,
      filename,
      module: tc.module,
      browser: "chromium",
      code: specCode,
      status: "ready",
      durationMs: 1400 + idx * 300,
    });
  });

  return specs;
}

